const FWD = POS_IDS.slice(0, 7);
const BACK = POS_IDS.slice(7);
function pos(all) { return Object.fromEntries(POS_IDS.map(p => [p, all])); }
function posSplit(fwd, back) {
  return Object.fromEntries([...FWD.map(p => [p, fwd]), ...BACK.map(p => [p, back])]);
}

